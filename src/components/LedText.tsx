const PITCH = 1.62; // app SCORE_FACE_PITCH
const GAP = 1; // columns between glyphs

const PALETTES = {
  white: { stops: ["#ffffff", "#f7fbfc", "#aeb8bd"], bloom: "#eaf7ff" },
  teal: { stops: ["#dff0fc", "#9bc2dc", "#6c93ae"], bloom: "#9bc2dc" },
} as const;

export default memo(function LedText({
  text,
  height = 12,
  color = "white",
  className = "",
}: {
  text: string;
  height?: number;
  color?: keyof typeof PALETTES;
  className?: string;
}) {
  const id = useId().replace(/[:]/g, "");
  const palette = PALETTES[color];
  const chars = text.toUpperCase().split("");

  const dots: { x: number; y: number }[] = [];
  let cursor = 0;
  chars.forEach((ch, i) => {
    const m = GLYPHS[ch];
    if (!m) return;
    if (i > 0) cursor += GAP;
    m.forEach((row, r) =>
      row.forEach((cell, c) => {
        if (cell === 1)
          dots.push({
            x: (cursor + c + 0.5) * PITCH,
            y: (r + 0.5) * PITCH,
          });
      })
    );
    cursor += m[0].length;
  });

  const width = cursor * PITCH;
  const heightUnits = 7 * PITCH;

  return (
    <svg
      viewBox={`0 0 ${width} ${heightUnits}`}
      style={{ height, width: (height / heightUnits) * width }}
      className={className}
      aria-hidden="true"
    >
      <defs>
        <radialGradient id={`led-${id}`} cx="50%" cy="42%" r="62%">
          <stop offset="0%" stopColor={palette.stops[0]} />
          <stop offset="46%" stopColor={palette.stops[1]} />
          <stop offset="100%" stopColor={palette.stops[2]} />
        </radialGradient>
      </defs>
      {dots.map((d, i) => (
        <g key={i}>
          <circle cx={d.x} cy={d.y} r={1.05} fill={palette.bloom} opacity={0.16} />
          <circle cx={d.x} cy={d.y} r={0.62} fill={`url(#led-${id})`} />
        </g>
      ))}
    </svg>
  );
});
